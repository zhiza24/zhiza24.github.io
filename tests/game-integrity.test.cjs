const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'../game_v5');
const flow=fs.readFileSync(path.join(root,'flow.js'),'utf8');
const entries=[...flow.matchAll(/\{u:'([^']+)',pt:'([^']+)'/g)].map(m=>({url:m[1],point:m[2]}));
assert.equal(entries.length,57,'approved route should contain 57 steps');
assert.equal(new Set(entries.map(x=>x.url)).size,entries.length,'route URLs must be unique');
entries.forEach(({url})=>{
 const file=url.split('?')[0];
 assert.ok(fs.existsSync(path.join(root,file)),'route target must exist: '+url);
});
const bg=entries.findIndex(x=>x.url==='slot.html?id=bg16');
const mechanism=entries.findIndex(x=>x.url==='slot.html?id=mechanism');
const km=entries.findIndex(x=>x.url==='slot.html?id=km');
assert.ok(bg>=0&&mechanism===bg+1&&km===mechanism+1,'BG16 -> inner mechanism -> Ideal Crooked World order');
const slot=fs.readFileSync(path.join(root,'slot.html'),'utf8');
const ordered=['background-state-16-data.js','background-state-16-engine.js','background-state-16.js','inner-mechanism-data.js','inner-mechanism.js'];
let last=-1;
ordered.forEach(name=>{const i=slot.indexOf('src="'+name);assert.ok(i>last,'slot must load '+name+' in dependency order');last=i});
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const cache=(sw.match(/const CACHE='([^']+)'/)||[])[1];
assert.ok(cache&&cache!=='alch-v5-static-2026-11-23-v30','PWA cache version must be bumped after asset changes');
const assets=[...sw.matchAll(/"\.\/([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(assets).size,assets.length,'precache list must not contain duplicates');
assets.forEach(a=>assert.ok(fs.existsSync(path.join(root,a)),'precache asset must exist: '+a));
ordered.forEach(name=>assert.ok(assets.includes(name),'new core module must be cached offline: '+name));
const ctx={window:{}};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,'inner-mechanism-data.js'),'utf8'),ctx);
const D=ctx.window.GIM_DATA;
assert.ok(D&&Array.isArray(D.sections));
assert.equal(D.sections.length,10,'inner mechanism must have ten sections');
const ids=[],usedFamilies=new Set();
D.sections.forEach((section,i)=>{
 assert.equal(section.items.length,6,'section '+(i+1)+' must have six items');
 section.items.forEach(item=>{
  ids.push(item[0]);
  usedFamilies.add(item[2]);
  assert.ok(D.families[item[2]],'every question family must have a display label: '+item[2]);
  assert.ok(item[3]==='resource'||item[3]==='protective','every item must belong to one explicit signal group');
 });
});
assert.equal(ids.length,60);
assert.equal(new Set(ids).size,60,'all 60 mechanism item IDs must be unique');
assert.deepEqual([...usedFamilies].sort(),Object.keys(D.families).sort(),'family dictionary must contain exactly the families used by the question bank');
assert.ok(slot.includes('inner-mechanism.js'),'mechanism must be loaded by the main task runner');
console.log('PASS: 57 route targets, route order, 10x6 mechanism bank, slot dependencies and offline precache.');
