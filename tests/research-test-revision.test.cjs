const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'../game_v5');
const dataContext={window:{}};
vm.createContext(dataContext);
vm.runInContext(fs.readFileSync(path.join(root,'tests-data.js'),'utf8'),dataContext);
const km=dataContext.window.GTESTS.km;
assert.equal(km.scales.length,6,'worldview test should retain six distinct interpretive dimensions');
assert.equal(km.scales.reduce((n,s)=>n+s.items.length,0),24,'worldview test should contain 24 items');
const ids=km.scales.flatMap(s=>s.items.map(q=>q.id));
assert.equal(new Set(ids).size,24,'all revised worldview item IDs must remain unique');
assert.equal(km.scales[0].name,'Объяснение неопределенности');
assert.equal(km.scales[2].name,'Толкование собственных чувств');
assert.equal(km.scales[4].name,'Объяснение успеха и неудачи');
assert.equal(km.scales[5].name,'Восприятие возможностей и ресурсов');
km.scales.forEach(scale=>{
 assert.equal(scale.items.length,4,scale.name+' should contain four items');
 assert.equal(scale.lv.length,4,scale.name+' should contain four interpretation levels');
});
const tests=fs.readFileSync(path.join(root,'tests.js'),'utf8');
assert.ok(tests.includes('scoringVersion:3'),'new wording must have its own scoring version');
assert.ok(tests.includes("have.scoringVersion!==3"),'older results must not be recalculated with revised wording');
assert.ok(tests.includes('Сохраненный результат прежней редакции остается в профиле'),'the old result must be preserved and explained');
assert.ok(tests.includes('Предыдущее исследование описывало повторяющиеся состояния'),'the test intro must distinguish state mapping from interpretation filters');
assert.ok(!tests.includes('answers:_d.answers||(built.res&&built.res.answers)||[]'),'raw answers must not be copied automatically into diary result cards');
const bg=fs.readFileSync(path.join(root,'background-state-16.js'),'utf8');
assert.ok(bg.includes('data-bg16-option'),'background test must use one shared choice list');
assert.ok(!bg.includes('data-bg16-secondary'),'background test must not render a duplicate secondary list');
assert.ok(bg.includes('Основной выбор отмечен'),'the role of the primary choice must be explicit');
assert.ok(!bg.includes('Баллы:'),'player-facing result must not expose raw technical scores');
const mirror=fs.readFileSync(path.join(root,'inner-mirror.js'),'utf8');
assert.ok(!mirror.includes("x.evidence.join"),'mirror diary must not append long raw answer lists');
assert.ok(mirror.includes('km.scoringVersion===3'),'mirror must use the matching interpretation bank for revised worldview results');
const swipe=fs.readFileSync(path.join(root,'swipe.html'),'utf8');
assert.ok(!swipe.includes("vs.map(function(v){return '«'+v+'»'}).join('<br>')"),'swipe result must not repeat every dismissed phrase');
assert.ok(swipe.includes('answers:[]'),'swipe diary must store the concise reflection, not duplicate the cards');
console.log('PASS: revised worldview bank, version-safe old results, one-list background choices and concise result summaries.');
