'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const store={alch_v5_profile:JSON.stringify({gender:'f',tracker:{events24:{'1':[{sphere:'work',motive:'own',emotion:'interest',after:'better'}]},marks24:{'2':[{sph:'relationships',kind:'act',init:'self',emo:'calm'}]},days:{'1':{sliders:{energy:7}}}},learning:{completed:{lesson1:{at:1}},attempts:{lesson1:2}}}),alch_samost:JSON.stringify({answers:{being:{notice:'...' },liking:{pleasant:'...'}},completed:{being:true,inner_voice:true,fake_topic:true},history:[{}]})};
const context={localStorage:{getItem:k=>store[k]||null,setItem:(k,v)=>{store[k]=v}},Date,JSON,Array,Object,String,Number,Math,isFinite};
context.window=context;vm.createContext(context);
vm.runInContext(fs.readFileSync('game_v5/pattern-map-engine.js','utf8'),context);
const api=context.GPatternMap;
let s=api.readSnapshot();
assert.equal(s.inventory.reactor.eventCount,1);
assert.equal(s.inventory.reactor.markCount,1);
assert.equal(s.inventory.reactor.daysWithRecords,2);
assert.equal(s.inventory.samost.completedTopics,2);
assert.equal(s.inventory.samost.totalTopics,9);
const before=[store.alch_v5_profile,store.alch_samost];
assert.equal(s.inventory.learning.completed,1);
assert.equal(store.alch_v5_profile.includes('tracker'),true);
assert.equal(store.alch_samost.includes('answers'),true);
assert.equal(api.addEpisode({sphere:'work',fact:'Не высказал идею',tag:'сложно высказаться'}).ok,true);
assert.equal(api.addEpisode({sphere:'relationships',fact:'Не обозначил желание',tag:'сложно высказаться'}).ok,true);
let p=api.analyze().patterns[0];
assert.equal(p.eligible,true);
assert.equal(p.sphereCount,2);
api.updatePattern(p.id,'partial','Зависит от контекста');
assert.equal(api.analyze().patterns[0].status,'partial');
assert.equal(api.addEpisode({sphere:'money',fact:'Здесь сказал',tag:'сложно высказаться',counterexample:true}).ok,true);
p=api.analyze().patterns[0];
assert.equal(p.episodes,2);
assert.equal(p.counterexamples,1);
assert.equal(p.sphereCount,2);
api.deleteEpisode(api.analyze().episodes[0].id);
assert.equal(api.analyze().patterns[0].eligible,false);
assert.equal(store.alch_v5_profile,before[0]);
assert.equal(store.alch_samost,before[1]);
assert.ok(store.alch_pattern_map_v1);
console.log('pattern-map-engine: all tests passed');
